def test_oncelik_sirasi_uygulanir_ve_zincir_durdurulabilir() -> None:
    ilk = kural(id=1, name="Önce", limits={"priority": 1, "endOtherRules": True})
    sonra = kural(id=2, name="Sonra", limits={"priority": 5},
                  action={"kind": "cart_fixed", "value": 5000})
    result = analytics.simulate(sepet(), [sonra, ilk], today=BUGUN)
    assert [row["name"] for row in result["applied"]] == ["Önce"]
    assert result["chainStopped"] == "Önce"
    assert "zinciri durdurdu" in result["skipped"][0]["reason"]


def test_zincir_durmazsa_iki_kural_ust_uste_biner() -> None:
    ilk = kural(id=1, name="Yüzde", limits={"priority": 1})
    sonra = kural(id=2, name="Sabit", limits={"priority": 2},
                  action={"kind": "cart_fixed", "value": 5000})
