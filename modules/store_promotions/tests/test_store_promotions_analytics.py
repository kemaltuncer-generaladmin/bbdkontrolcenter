"""Simülasyon, kupon önizlemesi ve performans — saf hesap, ağa çıkmaz.

Simülasyon motorunun işi indirim hesaplamak DEĞİL, kuralın yanlış yazıldığını
yazmadan önce göstermektir: koşul hiç tutmuyor, iki kampanya üst üste biniyor,
indirim sepetten büyük. Testler bu üç soruyu sorar.
"""

from __future__ import annotations

import random
from typing import Any

from store_promotions_backend import analytics

BUGUN = "2026-08-13"


def kural(**over: Any) -> dict[str, Any]:
    """Simülasyonun okuduğu ekran modeli (cart_rule_detail çıktısı biçiminde)."""
    base: dict[str, Any] = {
        "id": 1, "name": "Kural", "status": "active", "statusLabel": "Aktif",
        "couponType": "none", "code": "", "autoGenerated": False,
        "conditionType": "all", "conditions": [],
        "action": {"kind": "by_percent", "value": 10, "maxDiscount": 0, "freeShipping": False,
                   "step": 0, "quantity": 0},
        "limits": {"perCoupon": 0, "perCustomer": 0, "endOtherRules": False, "priority": 0},
        "usage": {"used": 0, "limit": 0, "ratio": None, "exhausted": False, "label": "0/sınırsız"},
        "channels": [], "customerGroups": [], "priority": 0, "freeShipping": False,
    }
    for key, value in over.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            base[key] = {**base[key], **value}
        else:
            base[key] = value
    return base


def sepet(*items: dict[str, Any], **over: Any) -> dict[str, Any]:
    cart = {"items": list(items) or [{"name": "Kalem", "price": 10000, "qty": 2,
                                      "productId": 5, "categoryIds": [4]}],
            "shipping": 3000, "paymentMethod": "cashondelivery", "customerGroupId": 2,
            "channelId": 1, "firstOrder": False}
    cart.update(over)
    return cart


# ============================================================== temel hesap

def test_yuzde_indirim_sepet_toplamindan_dusulur() -> None:
    result = analytics.simulate(sepet(), [kural()], today=BUGUN)
    assert result["subtotal"] == 20000
    assert result["discount"] == 2000
    assert result["payable"] == 20000 - 2000 + 3000


def test_yuzde_hesabi_kurus_kaybettirmez() -> None:
    # 2.943,00 ₺ × %30: `int(294300 * 0.3)` 88289 verir (float 88289.99999…),
    # doğrusu 88290. Bir kuruşluk sapma binlerce siparişte gözle görünür.
    result = analytics.simulate(
        sepet({"name": "X", "price": 294300, "qty": 1, "productId": 5, "categoryIds": []}),
        [kural(action={"kind": "by_percent", "value": 30})], today=BUGUN)
    assert result["discount"] == 88290


def test_ucretsiz_kargo_kargo_bedelini_sifirlar() -> None:
    result = analytics.simulate(sepet(), [kural(action={"freeShipping": True})], today=BUGUN)
    assert result["freeShipping"] is True
    assert result["payable"] == 20000 - 2000


