def test_x_al_y_ode_en_ucuz_kalemleri_bedava_yapar() -> None:
    cart = sepet({"name": "Ucuz", "price": 1000, "qty": 2, "productId": 1, "categoryIds": []},
                 {"name": "Pahalı", "price": 5000, "qty": 1, "productId": 2, "categoryIds": []})
    result = analytics.simulate(
        cart, [kural(action={"kind": "buy_x_get_y", "value": 0, "step": 2, "quantity": 1})],
        today=BUGUN)
    # 3 adet, 2 al 1 bedava → 1 adet bedava, en ucuz olan 10,00 ₺.
    assert result["discount"] == 1000


